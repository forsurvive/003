def main():
    img = Image.new("RGBA", (8 * len(ICONS), 8), (0, 0, 0, 0))
    px = img.load()
    for i, (name, rows) in enumerate(ICONS):
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
        for y in range(8):
            for x in range(8):
                if rows[y][x] == "#":
                    px[i * 8 + x, y] = (255, 255, 255, 255)
    out = os.path.join(ROOT, "game", "assets", "ui", "landmark_icons.png")
    img.save(out)
    big = Image.new("RGBA", (img.width * 6, img.height * 6), (20, 24, 20, 255))
    big.alpha_composite(img.resize((img.width * 6, img.height * 6), Image.NEAREST))
    big.save(os.path.join(ROOT, "art", "samples", "50_landmark_icons_x6.png"))
    print("원경 표식 %d:" % len(ICONS), out)


if __name__ == "__main__":
    main()
