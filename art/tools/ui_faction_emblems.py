def _hex(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def sheet16():
    img = Image.new("RGBA", (16 * len(CODES), 16), (0, 0, 0, 0))
    px = img.load()
    for i, c in enumerate(CODES):
        rows = S16[c]
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), c
        for y in range(16):
            for x in range(16):
                if rows[y][x] == "#":
                    px[i * 16 + x, y] = (255, 255, 255, 255)
    return img


