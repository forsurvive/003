def bitmap(rows):
    return [[1 if c in "#~" else 0 for c in r] for r in rows]


def outline(b):
    """채움 → 윤곽: 4이웃 중 하나라도 빈 칸(또는 가장자리)인 칸만 남긴다"""
    out = [[0] * 12 for _ in range(12)]
    for y in range(12):
        for x in range(12):
            if b[y][x] and any(not (0 <= x + dx < 12 and 0 <= y + dy < 12) or not b[y + dy][x + dx]
                               for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = 1
    return out


def main():
    img = Image.new("RGBA", (12 * 22, 24), (0, 0, 0, 0))
    px = img.load()
    for i in range(1, 23):
        rows = ICONS[i]
        assert len(rows) == 12 and all(len(r) == 12 for r in rows), i
        b = bitmap(rows)
        for row, bb in enumerate((b, outline(b))):
            for y in range(12):
                for x in range(12):
                    if bb[y][x]:
                        px[(i - 1) * 12 + x, row * 12 + y] = (255, 255, 255, 255)
    out = os.path.join(ROOT, "game", "assets", "ui", "map_icons.png")
    img.save(out)
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(os.path.join(ROOT, "art", "samples", "49_map_icons_x4.png"))
    print("지도 아이콘 22 × 2:", out)


if __name__ == "__main__":
    main()
