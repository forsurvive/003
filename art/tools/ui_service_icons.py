"""NPC 서비스 아이콘(SD-12 §4.9 이름표 왼쪽 8×8 · §3.11 인물 수첩): 1비트 도트, 흰색 + 알파 — 게임이 CRT·HUD 색으로 칠한다.
순서 = SD-07b §1.4 서비스 약자 '상 의 수 정 숙 통 지 동 교' + SD-12 §4.9의 물 상인 · 이동 상인(약자가 없어 뒤에 붙인다).
출력 game/assets/ui/service_icons.png (8×8 × 11열). python3 art/tools/ui_service_icons.py
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ICONS = [
    ("상", "상인(캡 주머니)", [".#....#.", "..####..", "...##...", ".######.", "########", "###..###", "###..###", ".######."]),
    ("의", "의사(십자)", ["..####..", "..####..", "########", "########", "########", "########", "..####..", "..####.."]),
    ("수", "수리(렌치)", ["#..#....", "#..#....", "####....", ".####...", "...###..", "....###.", ".....###", "......##"]),
    ("정", "정보·소문(말풍선)", [".######.", "########", "##.#.#.#", "########", ".######.", "..##....", ".##.....", "........"]),
    ("숙", "숙소(침대)", ["........", "#.......", "#.##....", "#.##....", "########", "########", "#......#", "#......#"]),
    ("통", "통행(차단봉)", ["##......", "##......", "########", "##.#.#.#", "########", "##......", "##......", "####...."]),
    ("지", "지원 병력(깃발)", ["#.......", "######..", "#######.", "######..", "#.......", "#.......", "#.......", "###....."]),
    ("동", "일시 동행(두 사람)", [".##...##", ".##...##", "........", "####.###", "####.###", ".##...#.", ".##...#.", ".##...#."]),
    ("교", "교습·비기(펼친 책)", ["........", "###..###", "#..##..#", "#.#..#.#", "#..##..#", "#.#..#.#", "###..###", "...##..."]),
    ("물", "물 상인(물방울)", ["...##...", "...##...", "..####..", ".######.", ".####.#.", ".###.##.", "..####..", "........"]),
    ("레", "이동 상인(수레)", ["#.......", ".#......", ".#######", ".#######", "..######", "........", "..##..##", "..##..##"]),
]


def main():
    img = Image.new("RGBA", (8 * len(ICONS), 8), (0, 0, 0, 0))
    px = img.load()
    for i, (_code, _name, rows) in enumerate(ICONS):
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), _name
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    px[i * 8 + x, y] = (255, 255, 255, 255)
    out = os.path.join(ROOT, "game", "assets", "ui", "service_icons.png")
    img.save(out)
    big = Image.new("RGBA", (img.width * 6 + (len(ICONS) - 1) * 6, 48), (11, 31, 16, 255))
    for i in range(len(ICONS)):
        tile = img.crop((i * 8, 0, i * 8 + 8, 8)).resize((48, 48), Image.NEAREST)
        big.paste(Image.new("RGBA", (48, 48), (124, 240, 142, 255)), (i * 54, 0), tile)
    big.save(os.path.join(ROOT, "art", "samples", "51_service_icons_x6.png"))
    print("서비스 아이콘 %d:" % len(ICONS), out)


if __name__ == "__main__":
    main()
